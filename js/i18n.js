window.I18N_DICTIONARY = I18N_DICTIONARY;

function applyI18nLanguage(lang) {
    const dict = I18N_DICTIONARY[lang] || I18N_DICTIONARY.az;
    document.documentElement.lang = lang;

    // Update all elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // Update all elements with data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key]) {
            el.setAttribute("placeholder", dict[key]);
        }
    });

    // Update Language Toggle Badge
    const flagEl = document.getElementById("lang-flag");
    const labelEl = document.getElementById("lang-label");
    if (flagEl && labelEl) {
        if (lang === "en") {
            flagEl.textContent = "🇬🇧";
            labelEl.textContent = "EN | AZ";
        } else {
            flagEl.textContent = "🇦🇿";
            labelEl.textContent = "AZ | EN";
        }
    }

    try {
        localStorage.setItem("skillmap_lang", lang);
    } catch(e) {}
}

window.applyI18nLanguage = applyI18nLanguage;
